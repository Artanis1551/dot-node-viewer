using System.Reflection;

namespace DotNodeViewer.Core.Tests;

/// <summary>
/// Verifies that the public API surface of <c>DotNodeViewer.Core</c> strictly encapsulates all internal I/O primitives,
/// format-specific parsers, and third-party serialization schemas.
/// </summary>
public sealed class PublicApiEncapsulationTests
{
    private static readonly string[]AllowedPublicNamespaces =
    [
        "DotNodeViewer.Core",
        "DotNodeViewer.Core.Ir",
        "DotNodeViewer.Core.Abstractions",
    ];

    private static readonly string[] ForbiddenNamespaceFragments =
    [
        "DotNodeViewer.Core.Formats",
        "DotNodeViewer.Core.IO",
        "Google.Protobuf",
        "Google.FlatBuffers",
        "FlatSharp",
        "PureHDF",
        "Avalonia",
        "SkiaSharp",
    ];

    [Test]
    public async Task ExportedTypes_AllResideInApprovedPublicNamespaces()
    {
        Assembly coreAssembly = typeof(CoreLibraryInfo).Assembly;
        Type[] exportedTypes = coreAssembly.GetExportedTypes();

        await Assert.That(exportedTypes.Length > 0).IsTrue();

        foreach (Type type in exportedTypes)
        {
            string ns = type.Namespace ?? string.Empty;
            bool isAllowed = Array.IndexOf(AllowedPublicNamespaces, ns) >= 0;
            await Assert.That(isAllowed).IsTrue();

            foreach (string forbidden in ForbiddenNamespaceFragments)
            {
                await Assert.That(type.FullName!.Contains(forbidden, StringComparison.OrdinalIgnoreCase)).IsFalse();
            }
        }
    }

    [Test]
    public async Task ExportedClassesAndRecords_AreSealedOrClosedDiscriminatedUnions()
    {
        Assembly coreAssembly = typeof(CoreLibraryInfo).Assembly;
        Type[] exportedTypes = coreAssembly.GetExportedTypes();

        foreach (Type type in exportedTypes)
        {
            if (type.IsInterface || type.IsValueType || type.IsEnum)
            {
                continue;
            }

            if (type.IsAbstract && !type.IsSealed)
            {
                // Abstract base records in the IR must not expose public or protected constructors to external assemblies.
                ConstructorInfo[] publicOrProtectedCtors = type.GetConstructors(
                    BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
                foreach (ConstructorInfo ctor in publicOrProtectedCtors)
                {
                    // Allow copy constructor (protected record(record original)) generated by C# compiler on abstract records,
                    // but forbid public or family (protected) parameterless/custom constructors that allow external derivation.
                    ParameterInfo[] parameters = ctor.GetParameters();
                    bool isCompilerCopyCtor = parameters.Length == 1 && parameters[0].ParameterType == type;
                    if (!isCompilerCopyCtor)
                    {
                        await Assert.That(ctor.IsPublic || ctor.IsFamily || ctor.IsFamilyOrAssembly).IsFalse();
                    }
                }

                continue;
            }

            await Assert.That(type.IsSealed).IsTrue();
        }
    }

    [Test]
    public async Task PublicSignatures_NeverExposeInternalFormatOrThirdPartySchemaTypes()
    {
        Assembly coreAssembly = typeof(CoreLibraryInfo).Assembly;
        Type[] exportedTypes = coreAssembly.GetExportedTypes();

        foreach (Type type in exportedTypes)
        {
            foreach (PropertyInfo prop in type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static))
            {
                await AssertTypeIsAllowedInPublicSignatureAsync(prop.PropertyType);
            }

            foreach (FieldInfo field in type.GetFields(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static))
            {
                await AssertTypeIsAllowedInPublicSignatureAsync(field.FieldType);
            }

            foreach (MethodInfo method in type.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                await AssertTypeIsAllowedInPublicSignatureAsync(method.ReturnType);
                foreach (ParameterInfo param in method.GetParameters())
                {
                    await AssertTypeIsAllowedInPublicSignatureAsync(param.ParameterType);
                }
            }

            foreach (ConstructorInfo ctor in type.GetConstructors(BindingFlags.Public | BindingFlags.Instance))
            {
                foreach (ParameterInfo param in ctor.GetParameters())
                {
                    await AssertTypeIsAllowedInPublicSignatureAsync(param.ParameterType);
                }
            }
        }
    }

    private static async Task AssertTypeIsAllowedInPublicSignatureAsync(Type type)
    {
        if (type.IsByRef || type.IsPointer || type.IsArray)
        {
            Type? elementType = type.GetElementType();
            if (elementType is not null)
            {
                await AssertTypeIsAllowedInPublicSignatureAsync(elementType);
            }

            return;
        }

        if (type.IsGenericParameter)
        {
            return;
        }

        if (type.IsGenericType)
        {
            foreach (Type arg in type.GetGenericArguments())
            {
                await AssertTypeIsAllowedInPublicSignatureAsync(arg);
            }
        }

        string fullName = type.FullName ?? type.Name;
        foreach (string forbidden in ForbiddenNamespaceFragments)
        {
            await Assert.That(fullName.Contains(forbidden, StringComparison.OrdinalIgnoreCase)).IsFalse();
        }
    }
}

